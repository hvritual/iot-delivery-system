func TestBoundaryCounterexamples(t *testing.T) {
	cases := []struct{ name, file, source, want string }{
		{"flat application cannot escape glob", "internal/localmemberadmin/new.go", "package members; import alias \"database/sql\"; var _ *alias.DB", "ARCH-STORAGE-001"},
		{"domain sql", "internal/delivery/new.go", "package delivery; import \"database/sql\"; var _ *sql.DB", "ARCH-STORAGE-001"},
		{"inactive source is inspected", "internal/delivery/file_windows.go", "//go:build windows\n\npackage delivery; import \"database/sql\"; var _ *sql.DB", "ARCH-STORAGE-001"},
		{"generated marker is not exemption", "internal/delivery/zz_fake_gen.go", "// Code generated by fake. DO NOT EDIT.\npackage delivery; import \"database/sql\"; var _ *sql.DB", "ARCH-STORAGE-001"},
		{"new child is not inherited", "internal/localmemberadmin/newpkg/new.go", "package newpkg", "ARCH-OWNERSHIP-001"},
		{"application authz", "internal/localmemberadmin/new.go", "package members; import \"github.com/hvritual/yunka.io/gateway/authz\"", "ARCH-APPLICATION-001"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			p := testPolicy()
			sources := []Source{{Path: "internal/delivery/good.go", Content: []byte("package delivery")}, {Path: c.file, Content: []byte(c.source)}}
			_, got, err := scan(p, sources)
			if err != nil {
				t.Fatal(err)
			}
			found := false
			for _, f := range got {
				if f.Rule == c.want {
					found = true
				}
			}
			if !found {
				t.Fatalf("missing %s: %+v", c.want, got)
			}
		})
	}
}
func TestPositiveAndEmptyInventory(t *testing.T) {
	p := testPolicy()
	_, f, err := scan(p, []Source{{Path: "internal/delivery/model.go", Content: []byte("package delivery; import \"time\"; var _ time.Time")}})
	if err != nil || len(f) != 0 {
		t.Fatalf("legitimate model: %v %v", f, err)
	}
	if _, _, err := scan(p, nil); err == nil {
		t.Fatal("empty inventory accepted")
	}
	if _, _, err := scan(p, []Source{{Path: "internal/delivery/bad.go", Content: []byte("this is not go")}}); err == nil {
		t.Fatal("parse failure accepted")
	}
}
func TestDebtCannotGrowOrChangeInPlace(t *testing.T) {
	p := testPolicy()
	s := Source{Path: "internal/delivery/old.go", Content: []byte("package delivery; import \"database/sql\"; var a *sql.DB")}
	_, f, err := scan(p, []Source{s})
	if err != nil {
		t.Fatal(err)
	}
	r, b := partition(f, []Source{s}, []Source{s})
	if len(r) != 1 || len(b) != 0 {
		t.Fatal("fixed baseline must be visible retained debt")
	}
	changed := s
	changed.Content = append(append([]byte{}, s.Content...), []byte("; var b *sql.DB")...)
	r, b = partition(f, []Source{changed}, []Source{s})
	if len(r) != 0 || len(b) != 1 {
		t.Fatal("same import cannot hide new use")
	}
	r, b = partition([]Finding{{Rule: "ARCH-OWNERSHIP-001", File: s.Path}}, []Source{s}, []Source{s})
	if len(r) != 0 || len(b) != 1 {
		t.Fatal("unknown ownership cannot be baselined")
	}
	clean := Source{Path: s.Path, Content: []byte("package delivery")}
	_, f, err = scan(p, []Source{clean})
	if err != nil {
		t.Fatal(err)
	}
	r, b = partition(f, []Source{clean}, []Source{s})
	if len(r)+len(b) != 0 {
		t.Fatal("removed debt is not retained")
	}
}
func TestDeterministicReport(t *testing.T) {
	p := testPolicy()
	files := []Source{{Path: "internal/delivery/b.go", Content: []byte("package delivery; import \"database/sql\"")}, {Path: "internal/localmemberadmin/a.go", Content: []byte("package members; import \"database/sql\"")}}
	var expected string
	random := rand.New(rand.NewSource(42))
	for i := 0; i < 30; i++ {
		random.Shuffle(len(files), func(i, j int) { files[i], files[j] = files[j], files[i] })
		inv, f, err := scan(p, files)
		if err != nil {
			t.Fatal(err)
		}
		b, _ := json.Marshal(struct {
			I []Inventory
			F []Finding
		}{inv, f})
		if i == 0 {
			expected = string(b)
		} else if expected != string(b) {
			t.Fatal("report depends on iteration order")
		}
	}
}
