// These are compiled counterexample programs, not substitutes for application
// authorization tests. No production mock credentials or PASS receipts are used.
func TestTypedRenamingAndPositiveNames(t *testing.T) {
	root := t.TempDir()
	write := func(name, content string) {
		t.Helper()
		p := filepath.Join(root, name)
		if err := os.MkdirAll(filepath.Dir(p), 0755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(content), 0644); err != nil {
			t.Fatal(err)
		}
	}
	write("go.mod", "module example.test/backend\n\ngo 1.23.0\n")
	write("internal/delivery/service.go", `package delivery
type Service struct{}
func (*Service) Create(){}
func NewService()*Service{return &Service{}}
type WorkItem struct{Title string}
`)
	write("internal/httpapi/http.go", `package httpapi
import renamed "example.test/backend/internal/delivery"
func bad(){operations:=renamed.NewService(); f:=operations.Create; f()}
func leak()*renamed.Service{return nil}
type wrapper struct{operations *renamed.Service}
func (w wrapper) bad(){w.operations.Create()}
type own struct{}
func (*own) Create(){}
func good(){svc:=&own{};svc.Create();_ = renamed.WorkItem{}}
`)
	p := testPolicy()
	f, err := typedScan(root, p)
	if err != nil {
		t.Fatal(err)
	}
	counts := map[string]int{}
	for _, x := range f {
		counts[x.Rule]++
		if x.File != "internal/httpapi/http.go" {
			t.Fatalf("wrong provenance: %+v", x)
		}
	}
	if counts["ARCH-WRITE-001"] != 3 || counts["ARCH-WRITE-002"] != 2 || len(f) != 5 {
		t.Fatalf("wanted constructor, two raw-type uses, and both canonical method references: %+v", f)
	}
}
